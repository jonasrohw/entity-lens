"""Typeset the two selected appendix tables from verified correlation records."""

import csv
import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SOURCE = ROOT / "code/results/shared_baselines/correlations.csv"
OUT = ROOT / "paper/generated/shared_baselines"
MODELS = [
    ("olmo3_7b", "OLMo 3 7B"),
    ("gptj", "GPT-J 6B"),
    ("mistral7b", "Mistral 7B"),
    ("gemma2_9b", "Gemma 2 9B"),
    ("qwen3_8b_base", "Qwen3 8B Base"),
    ("qwen3_8_27b", "Qwen3.8 27B"),
    ("pythia6_9b", r"Pythia 6.9B$^{\dagger}$"),
]
READOUTS = [
    ("differential", r"\shortstack[r]{Differential\\Jacobian}"),
    ("raw_jacobian", r"\shortstack[r]{Raw\\Jacobian}"),
    ("logit_lens", "Logit lens"),
    ("differential_logit_lens", r"\shortstack[r]{Differential\\logit lens}"),
    ("geva_attribute_rate", r"\shortstack[r]{Attribute\\rate}"),
]
FREQUENCIES = [
    (
        "Marginal frequencies",
        [
            ("corpus_subject_count", r"Subject frequency, $c_s$"),
            ("corpus_object_count", r"Object frequency, $c_o$"),
        ],
    ),
    (
        "Co-occurrence",
        [
            ("corpus_cooccurrence", r"Joint frequency, $c_{so}$"),
            ("corpus_log1p_cooccurrence", r"Mean of $\log(1+c_{so})$"),
            ("corpus_log_mean_cooccurrence", r"$\log(1+\mathrm{mean}(c_{so}))$"),
        ],
    ),
    (
        "Conditional frequencies",
        [
            ("corpus_p_object_given_subject", r"Forward conditional, $P(o\mid s)$"),
            ("corpus_p_subject_given_object", r"Reverse conditional, $P(s\mid o)$"),
            (
                "corpus_direction_difference",
                r"Directional difference, $P(o\mid s)-P(s\mid o)$",
            ),
            ("corpus_micro_p_object_given_subject", r"Micro-averaged $P(o\mid s)$"),
            ("corpus_micro_p_subject_given_object", r"Micro-averaged $P(s\mid o)$"),
        ],
    ),
]


def coefficient(value, bold=False):
    sign = "-" if value < 0 else r"\phantom{-}"
    digits = f"{abs(value):.3f}"
    return "$" + sign + (r"\mathbf{" + digits + "}" if bold else digits) + "$"


def pvalue(value):
    if value < 0.001:
        mantissa, exponent = f"{value:.2e}".split("e")
        return "$" + mantissa + r"\times10^{" + str(int(exponent)) + "}$"
    return f"${value:.3f}$"


def main():
    with SOURCE.open() as stream:
        records = list(csv.DictReader(stream))

    def lookup(model, feature):
        matches = [
            r
            for r in records
            if r["model"] == model
            and r["feature"] == feature
            and r["category"] == "primary"
            and r["cohort"] == "all_25"
            and r["scope"] == "all_stages"
            and r["subset"] == "all"
            and r["outcome"] == "faithfulness"
        ]
        assert len(matches) == 1 and int(matches[0]["n"]) == 25, (model, feature)
        return matches[0]

    OUT.mkdir(parents=True, exist_ok=True)
    first = [
        r"% Generated by code/scripts/format_shared_baseline_tables.py.",
        r"\begin{table}[!htbp]",
        r"\centering",
        r"\caption{\textbf{Readout baselines across seven models.} Spearman correlation $\rho$ with LRE faithfulness on 25 shared-split relations per model. All neural readouts use the same newline-prefixed neutral prompt.}",
        r"\label{tab:shared-lenses-spearman}",
        r"\begingroup",
        r"\small",
        r"\renewcommand{\arraystretch}{1.18}",
        r"\setlength{\tabcolsep}{3pt}",
        r"\begin{tabular*}{\linewidth}{@{\extracolsep{\fill}}lrrrrr@{}}",
        r"\toprule",
        "Model & " + " & ".join(h for _, h in READOUTS) + r" \\",
        r"\midrule",
    ]
    for model, label in MODELS:
        values = [
            float(lookup(model, feature)["spearman_rho"]) for feature, _ in READOUTS
        ]
        first.append(
            label
            + " & "
            + " & ".join(coefficient(v, v == max(values)) for v in values)
            + r" \\"
        )
    first += [
        r"\bottomrule",
        r"\end{tabular*}",
        r"\endgroup",
        r"\par\vspace{5pt}",
        r"\begin{minipage}{\linewidth}\footnotesize",
        r"Bold marks the largest point estimate within each model, not a significant difference. $^{\dagger}$Pythia's attribute rate excludes 413 test rows with no predictions surviving the attribute filter; the other models have no undefined rates.",
        r"\end{minipage}",
        r"\end{table}",
        "",
    ]
    (OUT / "readout_comparison.tex").write_text("\n".join(first))

    second = [
        r"% Generated by code/scripts/format_shared_baseline_tables.py.",
        r"\begin{table}[!htbp]",
        r"\centering",
        r"\caption{\textbf{Frequency baselines for OLMo 3 7B.} Correlations with LRE faithfulness across the same 25 shared-split relations, using document counts from OLMo's three published training mixes combined.}",
        r"\label{tab:shared-corpus-spearman}",
        r"\begingroup",
        r"\small",
        r"\renewcommand{\arraystretch}{1.16}",
        r"\setlength{\tabcolsep}{6pt}",
        r"\begin{tabular*}{\linewidth}{@{\extracolsep{\fill}}lrr@{}}",
        r"\toprule",
        r"Frequency measure & Spearman $\rho$ & $p$-value \\",
        r"\midrule",
    ]
    for i, (group, features) in enumerate(FREQUENCIES):
        if i:
            second.append(r"\addlinespace[5pt]")
        second.append(r"\multicolumn{3}{@{}l}{\textit{" + group + r"}} \\")
        second.append(r"\addlinespace[2pt]")
        for feature, label in features:
            row = lookup("olmo3_7b", feature)
            second.append(
                label
                + " & "
                + coefficient(float(row["spearman_rho"]))
                + " & "
                + pvalue(float(row["spearman_p"]))
                + r" \\"
            )
    second += [
        r"\bottomrule",
        r"\end{tabular*}",
        r"\endgroup",
        r"\par\vspace{5pt}",
        r"\begin{minipage}{\linewidth}\footnotesize",
        r"Counts denote binary document presence. Means use the current test rows with both marginals observed; micro averages are ratios of summed counts. The $p$-values are two-sided and unadjusted.",
        r"\end{minipage}",
        r"\end{table}",
        "",
    ]
    (OUT / "olmo_frequencies.tex").write_text("\n".join(second))
    manifest = dict(
        source="code/results/shared_baselines/correlations.csv",
        source_sha256=hashlib.sha256(SOURCE.read_bytes()).hexdigest(),
        generator_sha256=hashlib.sha256(Path(__file__).read_bytes()).hexdigest(),
        readout_cells=35,
        frequency_rows=10,
        output_sha256={
            p.name: hashlib.sha256(p.read_bytes()).hexdigest()
            for p in [OUT / "readout_comparison.tex", OUT / "olmo_frequencies.tex"]
        },
    )
    (OUT / "presentation_manifest.json").write_text(
        json.dumps(manifest, indent=2) + "\n"
    )
    print(
        "Generated five-readout comparison and OLMo-only frequency table (45 verified records)."
    )


if __name__ == "__main__":
    main()
